// TORQUE as FRACTURE (B_n -> P_n).
//
// A fracture probe is a deliberately failing test generated from one
// HUMAN_FINAL / REG-accepted genuine-remainder BRIDGEGAP (the boundary). It
// asks the current structure to express what the boundary's own recipe needs
// and is expected to stop. The first truthful stoppage is boundary evidence.
// The probe carries no fix and edits no existing file.
//
// The probe travels the existing program patch path: it is admitted as a
// PROGRAM_PATCH candidate kin-linked (origin) to the boundary, waits for
// HUMAN_FINAL, needs an explicit Q for GITHUB:PROGRAM before it is applied
// and run, and is never picked up by the safe-action scan. When run, the
// existing GITHUB:PROGRAM executor applies it, runs go test, rolls a failure
// back, and the existing execution-signal capture records the result as
// evidence (execution_failed or execution_succeeded) with the travelling
// TransitionEmergIONID. A probe never writes a fact that closes the gap.

const fractureProbeReasonerName = "torque-fracture-probe"

// fractureProbePath names the generated test file from the boundary IDN.
// Probe files live in their own test-only package, probes/.
func fractureProbePath(boundaryID string) string {
	name := strings.ToLower(strings.TrimSpace(boundaryID))
	name = strings.ReplaceAll(name, "-", "_")
	return "probes/fracture_" + name + "_test.go"
}

// fractureBoundary validates that em is a recorded genuine-remainder
// BRIDGEGAP and returns its gap token and requirement.
func fractureBoundary(em core.EmergION) (string, string, error) {
	if em.REL["source_kind"] != "TARGET_COMPARISON" {
		return "", "", fmt.Errorf("fracture boundary %s is not a TARGET_COMPARISON", em.IDN)
	}
	if len(em.VAL.Gaps) != 1 {
		return "", "", fmt.Errorf("fracture boundary %s carries %d gaps, want exactly one", em.IDN, len(em.VAL.Gaps))
	}
	required := strings.TrimSpace(em.REL["required_capability"])
	gap := genuineRemainderBridgeGap(required, em.REL["requirement_basis"])
	if gap == "" || gap != em.VAL.Gaps[0] {
		return "", "", fmt.Errorf("fracture boundary %s has no genuine-remainder BRIDGEGAP", em.IDN)
	}
	return gap, required, nil
}

// renderFractureProbe deterministically renders the probe test from the
// boundary's own structure: IDN, target link, gap token, requirement basis,
// target state, Differences, evidence hash and the existing recipe for the
// requirement. Nothing else is read.
func renderFractureProbe(em core.EmergION) ([]byte, error) {
	gap, required, err := fractureBoundary(em)
	if err != nil {
		return nil, err
	}
	recipe := requiredCapabilityRecipe(required)
	if len(recipe) == 0 {
		return nil, fmt.Errorf("fracture boundary %s requirement %s has no recipe", em.IDN, required)
	}

	quoted := func(values []string) string {
		parts := make([]string, 0, len(values))
		for _, value := range values {
			parts = append(parts, fmt.Sprintf("%q", value))
		}
		return "[]string{" + strings.Join(parts, ", ") + "}"
	}
	differences := append([]string(nil), em.VAL.Differences...)
	sort.Strings(differences)
	funcName := "TestFracture" + strings.ReplaceAll(strings.TrimSpace(em.IDN), "-", "_")

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by the UNIFUSION TORQUE fracture probe. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Boundary %s, %s. This probe is expected to fail: its first\n", em.IDN, gap)
	fmt.Fprintf(&b, "// stoppage is boundary evidence. It carries no fix.\n\n")
	fmt.Fprintf(&b, "package probes\n\n")
	fmt.Fprintf(&b, "import (\n\"testing\"\n\n\"emergion-sovereign-runtime/internal/adapters\"\n)\n\n")
	fmt.Fprintf(&b, "func %s(t *testing.T) {\n", funcName)
	fmt.Fprintf(&b, "boundary := %q\n", em.IDN)
	fmt.Fprintf(&b, "targetEmergION := %q\n", em.REL["target_emergion"])
	// The gap is printed without its BRIDGEGAP: prefix so probe output is
	// never re-read as a gap token by the execution-signal capture.
	fmt.Fprintf(&b, "gap := %q\n", strings.TrimPrefix(gap, "BRIDGEGAP:"))
	fmt.Fprintf(&b, "basis := %q\n", em.REL["requirement_basis"])
	fmt.Fprintf(&b, "required := %q\n", required)
	fmt.Fprintf(&b, "targetState := %q\n", strings.TrimSpace(em.REL["target_state"]))
	fmt.Fprintf(&b, "differences := %s\n", quoted(differences))
	fmt.Fprintf(&b, "boundaryEvidence := %q\n", em.MEM.SourceHash)
	fmt.Fprintf(&b, "recipe := %s\n\n", quoted(recipe))
	fmt.Fprintf(&b, "t.Logf(\"FRACTURE_PROBE boundary=%%s target=%%s gap=%%s basis=%%s required=%%s target_state=%%q differences=%%q evidence=%%s\", boundary, targetEmergION, gap, basis, required, targetState, differences, boundaryEvidence)\n\n")
	fmt.Fprintf(&b, "// Ask the current structure to express every recipe token.\n")
	fmt.Fprintf(&b, "expressed := map[string]bool{}\n")
	fmt.Fprintf(&b, "for _, adapter := range adapters.Catalog(true) {\nfor _, capability := range adapter.Capabilities {\nexpressed[capability] = true\n}\n}\n")
	fmt.Fprintf(&b, "for _, token := range recipe {\nif !expressed[token] {\n")
	fmt.Fprintf(&b, "t.Fatalf(\"FRACTURE_STOPPAGE boundary=%%s gap=%%s required=%%s token=%%s: no adapter expresses recipe token\", boundary, gap, required, token)\n")
	fmt.Fprintf(&b, "}\n}\n}\n")

	return format.Source(b.Bytes())
}

// fractureProbePatch renders a new-file unified Git diff for the probe.
func fractureProbePatch(path string, content []byte) []byte {
	lines := strings.Split(strings.TrimSuffix(string(content), "\n"), "\n")
	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%s b/%s\n", path, path)
	b.WriteString("new file mode 100644\n")
	b.WriteString("--- /dev/null\n")
	fmt.Fprintf(&b, "+++ b/%s\n", path)
	fmt.Fprintf(&b, "@@ -0,0 +1,%d @@\n", len(lines))
	for _, line := range lines {
		b.WriteString("+")
		b.WriteString(line)
		b.WriteString("\n")
	}
	return []byte(b.String())
}

// ProposeOneFractureProbe admits at most one fracture probe proposal for the
// first accepted genuine-remainder BRIDGEGAP that has none yet. The proposal
// is only admitted to GOV; it is never authorized, applied or run here.
func (r Runtime) ProposeOneFractureProbe(
	ctx context.Context,
	workDir string,
) (core.EmergION, bool, error) {
	if r.Store == nil {
		return core.EmergION{}, false, fmt.Errorf("runtime store not configured")
	}
	events, err := r.Store.Events()
	if err != nil {
		return core.EmergION{}, false, err
	}
	st, err := livefield.Rebuild(events)
	if err != nil {
		return core.EmergION{}, false, err
	}
	boundaryState, governedState, err := r.governedStateContext()
	if err != nil {
		return core.EmergION{}, false, err
	}

	ids := make([]string, 0, len(st.Accepted))
	for id := range st.Accepted {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	for _, id := range ids {
		boundary := st.Accepted[id]
		gap, _, err := fractureBoundary(boundary)
		if err != nil {
			continue
		}
		if programPatchPending(st, boundary.IDN) {
			continue
		}

		content, err := renderFractureProbe(boundary)
		if err != nil {
			return core.EmergION{}, false, err
		}
		em, duplicate, err := r.admitFractureProbe(ctx, boundary, gap,
			fractureProbePath(boundary.IDN), content, nil, workDir, boundaryState, governedState)
		if err != nil {
			return em, false, err
		}
		if duplicate {
			continue
		}
		return em, true, nil
	}
	return core.EmergION{}, false, nil
}

// admitFractureProbe checks the probe as a single new-file patch in workDir
// and admits it as a PROGRAM_PATCH candidate kin-linked (origin) to the
// boundary. extra carries further runtime-owned probe linkage.
func (r Runtime) admitFractureProbe(
	ctx context.Context,
	boundary core.EmergION,
	gap string,
	path string,
	content []byte,
	extra map[string]string,
	workDir string,
	boundaryState core.State,
	governedState string,
) (core.EmergION, bool, error) {
	patch := fractureProbePatch(path, content)
	if _, err := adapters.CheckGitHubProgramPatch(workDir, patch); err != nil {
		return core.EmergION{}, false, fmt.Errorf("fracture probe patch rejected: %w", err)
	}

	relationships := map[string]string{
		"source_name":    path,
		"source_kind":    "PROGRAM_PATCH",
		"program_target": path,
		"fracture_gap":   gap,
	}
	keys := make([]string, 0, len(extra))
	for key := range extra {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		relationships[key] = extra[key]
	}

	analysis := reason.Result{
		Summary:       "TORQUE fracture probe proposal for " + boundary.IDN,
		Relationships: relationships,
		Capabilities:  []string{"PROGRAM"},
		Facts:         []string{"fracture probe proposal preserved"},
		Risk:          "H",
		Facets:        []string{"PROGRAM_FORGE"},
	}

	probeRuntime := r
	probeRuntime.Reasoner = fixedReasoner{
		name:    fractureProbeReasonerName,
		version: "v1",
		result:  analysis,
	}
	return probeRuntime.admitAnalyzedCandidate(
		ctx,
		path,
		patch,
		"torque_fracture_probe",
		boundaryState,
		governedState,
		boundary.IDN,
		analysis,
	)
}

// withoutFractureProbeEvidence removes fracture probes and the execution
// records observed from them from the accepted reality a TARGET is compared
// against. A probe produces evidence only: neither the probe's own PROGRAM
// capability nor its execution signal may stand in for the fact,
// relationship or capability the boundary is missing. When no probe exists
// the reality, and so the comparison evidence, is unchanged.
func withoutFractureProbeEvidence(reality map[string]core.EmergION) map[string]core.EmergION {
	probes := map[string]bool{}
	for id, em := range reality {
		if strings.TrimSpace(em.REL["fracture_gap"]) != "" {
			probes[id] = true
		}
	}
	if len(probes) == 0 {
		return reality
	}
	out := make(map[string]core.EmergION, len(reality))
	for id, em := range reality {
		if probes[id] {
			continue
		}
		switch em.REL["source_kind"] {
		case "EXECUTION_RESULT", "EXECUTION_OBSERVATION":
			if probes[strings.TrimSpace(em.REL["kin_emergion"])] {
				continue
			}
		}
		out[id] = em
	}
	return out
}
